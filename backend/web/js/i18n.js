let lang = 'vi';
try { lang = localStorage.getItem('kz_lang') || ''; } catch { /* storage blocked */ }
if (!LANGS.some((l) => l.code === lang)) {
  const n = (navigator.language || 'vi').slice(0, 2).toLowerCase();
  lang = LANGS.some((l) => l.code === n) ? n : 'vi';
}

export const getLang = () => lang;
export const locale = () => LANGS.find((l) => l.code === lang).locale;
export function setLang(code) {
  lang = code;
  try { localStorage.setItem('kz_lang', code); } catch { /* ignore */ }
  document.documentElement.lang = code;
}

// Translate a key and fill {params}. Params are inserted as given (callers escape user data).
export function t(key, params) {
  let s = key;
  if (lang !== 'vi' && D[key]) s = D[key][IDX[lang]] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  return s;
}

// Translate static Vietnamese text already in the DOM (text nodes and a few attributes).
const ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];
function trText(node) {
  const raw = node.nodeValue, key = raw.trim();
  if (!key || !D[key]) return;
  node.nodeValue = raw.replace(key, D[key][IDX[lang]]);
}
const SKIP = { acceptNode: (n) => (n.nodeType === 1 && (n.tagName === 'SCRIPT' || n.tagName === 'STYLE' || n.hasAttribute('data-notr')) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT) };
function trAttrs(el) {
  for (const a of ATTRS) { const v = el.getAttribute(a); if (v && D[v.trim()]) el.setAttribute(a, D[v.trim()][IDX[lang]]); }
}
export function translateTree(root) {
  if (lang === 'vi' || !root) return;
  if (root.nodeType === 3) { if (!root.parentElement?.closest('[data-notr]')) trText(root); return; }
  if (root.nodeType !== 1 || root.closest('[data-notr]')) return;
  trAttrs(root);
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, SKIP);
  let n;
  while ((n = w.nextNode())) n.nodeType === 3 ? trText(n) : trAttrs(n);
}
export function startAutoTranslate() {
  document.documentElement.lang = lang;
  translateTree(document.body);
  new MutationObserver((muts) => {
    if (lang === 'vi') return;
    for (const m of muts) m.addedNodes.forEach((n) => translateTree(n));
  }).observe(document.body, { childList: true, subtree: true });
}
